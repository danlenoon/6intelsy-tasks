import nltk
from nltk.tokenize import word_tokenize
from nltk.tag import pos_tag

# Download necessary NLTK data files
nltk.download('punkt')
nltk.download('averaged_perceptron_tagger_eng')
nltk.download('punkt_tab')

# Function to categorize words in the text
def categorize_words(text):
    # Tokenize the text
    words = word_tokenize(text)

    # Tag the words with part of speech
    tagged_words = pos_tag(words)

    # Initialize the dictionary to store categorized words
    categorized_words = {
        'Nouns': [],
        'Verbs': [],
        'Adjectives': [],
        'Pronouns': [],
        'Others': []
    }

    # Categorize words based on their part of speech
    for word, tag in tagged_words:
        if tag.startswith('NN'):
            categorized_words['Nouns'].append(word)
        elif tag.startswith('VB'):
            categorized_words['Verbs'].append(word)
        elif tag.startswith('JJ'):
            categorized_words['Adjectives'].append(word)
        elif tag.startswith('PRP'):
            categorized_words['Pronouns'].append(word)
        else:
            categorized_words['Others'].append(word)

    return categorized_words

if __name__ == "__main__":
    # Ask user for input text
    user_input = input("Enter a sentence: ")

    # Get categorized words
    result = categorize_words(user_input)

    # Print the categorized words
    print("Categorized words:", result)