def diagnose_computer_issue():
  print("COMPUTER ISSUE DIAGNOSIS EXPERT SYSTEM")
  print("This expert system can diagnose the following issues but limited to three only:")
  print("1. Computer won't turn on")
  print("2. Keyboard won't register from user's input")
  print("3. No internet connection")

  choice = input("Enter your choice: ")

  if choice == "1":
    print("\nDiagnosing: Computer won't turn on")
    power = input("Is the power cable plugged in properly? ").lower()

    if power == "no":
      print("Diagnosis: Plug in the power cable securely and try again.")

    else:
      outlet = input("Is the power outlet working (try another device)? ").lower()

      if outlet == "no":
        print("Diagnosis: Use a different power outlet or extension cord.")
      else:
        supply = input("Do you hear any fan noise or see lights? ").lower()

        if supply == "no":
          print("Diagnosis: The power supply or motherboard may be faulty.")
        else:
          print("Diagnosis: Try restarting or checking your monitor connections.")

    return

  elif choice == "2":
    print("\nDiagnosing: Keyboard won't register from the user's input")
    power = input("Is the computer turned on? ").lower()

    if power == "no":
      print("Diagnosis: Turn on your computer first, then try typing again.")
      return

    wireless = input("Is your keyboard wireless? ").lower()

    if wireless == "yes":
      battery = input("Are the batteries charged or new? ").lower()

      if battery == "no":
        print("Diagnosis: Replace or recharge the keyboard batteries.")
        return
      else:
        connect = input("Is the wireless receiver or Bluetooth connected properly? ").lower()\

        if connect == "no":
          print("Diagnosis: Reconnect your Bluetooth or wireless USB receiver.")
          return
        else:
          print("Diagnosis: Re-pair (not repair) the keyboard in Bluetooth settings.")
          return

    else:
      cable = input("Is the keyboard plugged securely into the USB port? ").lower()

      if cable == "no":
        print("Diagnosis: Plug in the keyboard securely to the USB port.")
        return
      else:
        driver = input("Does the keyboard work in BIOS or another computer? ").lower()

        if driver == "yes":
          print("Diagnosis: Keyboard driver may be corrupted. Reinstall the driver in Device Manager.")
        else:
          print("Diagnosis: Keyboard hardware may be damaged. Consider replacing it.")

    return

  elif choice == "3":
    print("\nDiagnosing: No internet connection")
    wifi = input("Is your Wi-Fi turned on? ").lower()

    if wifi == "no":
      print("Diagnosis: Turn on your Wi-Fi and reconnect to your network.")
    else:
      router = input("Are the router's indicator lights working? ").lower()

      if router == "no":
        print("Diagnosis: Restart your router and check the cables.")
      else:
        other_devices = input("Can other devices connect to the internet? ").lower()

        if other_devices == "no":
          print("Diagnosis: Contact your Internet Service Provider (ISP).")
        else:
          print("Diagnosis: Run Windows Network Troubleshooter or reset network settings.")

    return

  else:
    print("\nINVALID INPUT. Kindly input 1, 2, or 3 only.")

diagnose_computer_issue()