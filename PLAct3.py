import time
import heapq
import tracemalloc

graph = {'A': ['B', 'C'], 'B': ['D', 'E'], 'C': ['F'], 'D': [], 'E': ['F'], 'F': []}
heuristic = {'A': 6, 'B': 4, 'C': 4, 'D': 2, 'E': 2, 'F': 0}

def bfs(start, goal):
  visited = set()
  queue = [start]

  while queue:
    node = queue.pop(0)

    if node == goal:
      return True

    visited.add(node)

    for neighbor in graph[node]:
      if neighbor not in visited:
        queue.append(neighbor)

  return False

def dfs(start, goal):
  visited = set()
  stack = [start]

  while stack:
    node = stack.pop()

    if node == goal:
      return True

    visited.add(node)

    for neighbor in reversed(graph[node]):
      if neighbor not in visited:
        stack.append(neighbor)

  return False

def best_first_search(start, goal):
  visited = set()
  pq = []
  heapq.heappush(pq, (heuristic[start], start))

  while pq:
    _, node = heapq.heappop(pq)

    if node == goal:
      return True

    visited.add(node)

    for neighbor in graph[node]:
      if neighbor not in visited:
        heapq.heappush(pq, (heuristic[neighbor], neighbor))

  return False

def a_star(start, goal):
  visited = set()
  pq = []
  heapq.heappush(pq, (0 + heuristic[start], 0, start))

  while pq:
    f, g, node = heapq.heappop(pq)

    if node == goal:
      return True

    visited.add(node)

    for neighbor in graph[node]:
      if neighbor not in visited:
        new_g = g + 1
        new_f = new_g + heuristic[neighbor]
        heapq.heappush(pq, (new_f, new_g, neighbor))

  return False

def measure_performance(func, start, goal):
  tracemalloc.start()
  t1 = time.perf_counter()
  start_time = time.time()
  result = func(start, goal)
  end_time = time.time()
  time_n = end_time - start_time
  t2 = time.perf_counter()
  memory_current, memory_peak = tracemalloc.get_traced_memory()
  tracemalloc.stop()

  return {"result": result, "perf_time": t2 - t1, "time_n": time_n, "space_used_bytes": memory_peak}

if __name__ == "__main__":
  start, goal = 'A', 'F'
  algorithms = {"Breadth First Search": bfs, "Depth First Search": dfs, "Best-First Search": best_first_search, "A* Search Algorithm": a_star}

  for name, algo in algorithms.items():
    perf = measure_performance(algo, start, goal)
    print(f"\n{name}")
    print(f"Found Goal: {perf['result']}")
    print(f"Perf Counter Time: {perf['perf_time']:.10f} seconds")
    print(f"Time_n: {perf['time_n']:.10f} seconds")
    print(f"Space Used: {perf['space_used_bytes']} bytes")